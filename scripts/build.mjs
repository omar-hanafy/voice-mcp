#!/usr/bin/env node
// Bundles src/main.ts into the self-contained runtime that ships in the plugin.
import { chmodSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { version, engines } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
// Compile for the oldest supported Node.js so the bundle never relies on newer syntax.
const minNode = /^>=(\d+)$/.exec(engines?.node ?? '')?.[1];
if (!minNode) throw new Error(`package.json engines.node must look like ">=22", got ${JSON.stringify(engines?.node)}`);

await build({
  entryPoints: [join(root, 'src/main.ts')],
  outfile: join(root, 'plugin/dist/voice-mcp.mjs'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: `node${minNode}`,
  legalComments: 'none',
  charset: 'utf8',
  define: { __VOICE_MCP_VERSION__: JSON.stringify(version) },
  banner: {
    // Bundled CommonJS dependencies may call require(); give them one in ESM.
    js: [
      '#!/usr/bin/env node',
      `// voice-mcp ${version} - generated by scripts/build.mjs; edit src/ instead.`,
      "import { createRequire as __voiceMcpCreateRequire } from 'node:module';",
      'const require = __voiceMcpCreateRequire(import.meta.url);',
    ].join('\n'),
  },
  logLevel: 'warning',
});
// Executable so `voice-mcp` works as an npm bin and when invoked directly on macOS/Linux.
chmodSync(join(root, 'plugin/dist/voice-mcp.mjs'), 0o755);
console.log(`built plugin/dist/voice-mcp.mjs (v${version})`);
